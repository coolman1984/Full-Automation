"""Regenerate or verify the tool catalog and the repository skill mirrors."""
import argparse
import inspect
import json
from pathlib import Path
import re
import sys
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from full_automation import __version__
from full_automation.engine import Engine

CATALOG = ROOT / "docs/reference/TOOLS.md"
CANONICAL = ROOT / ".claude/skills"
MIRROR = ROOT / ".agents/skills"
GROUPS = {
    "system": "Environment and controls",
    "browser": "Chrome and CDP",
    "desktop": "Windows desktop",
    "recording": "Human demonstration",
    "agent": "Managed agents and transcripts",
    "transcript": "Managed agents and transcripts",
    "workflow": "Workflows and run history",
    "schedule": "Task Scheduler",
    "file": "Output evidence",
}


def describe_type(spec):
    if "anyOf" in spec:
        return "/".join(describe_type(item) for item in spec["anyOf"])
    return spec.get("type", "any")


def catalog():
    with TemporaryDirectory() as directory, Engine(directory) as engine:
        tools = list(engine.tools.values())
    groups = {}
    for tool in tools:
        group = GROUPS.get(tool.name.split("_", 1)[0], "Other")
        groups.setdefault(group, []).append(tool)
    lines = ["# Tool catalog", "",
             "<!-- Generated by scripts/docs_check.py. Edit the tool registry to update. -->", "",
             f"Version {__version__} · {len(tools)} tools · [Project map](../PROJECT_MAP_AR.md)", "",
             "Required arguments are marked with `*`. Optional parameters show defaults where available.",
             "Effect flags come from the registered tool's annotations. See the map for test evidence.", ""]
    for group, items in groups.items():
        lines.extend([f"## {group}", "", "| Tool | Arguments | Effect | Use | Source |",
                      "|---|---|---|---|---|"])
        for tool in items:
            parameters = []
            required = set(tool.schema["required"])
            for name, spec in tool.schema["properties"].items():
                marker = "*" if name in required else ""
                default = "=" + json.dumps(spec["default"], ensure_ascii=False) if "default" in spec else ""
                parameters.append(f"`{name}{marker}: {describe_type(spec)}{default}`")
            arguments = ", ".join(parameters) or "—"
            source = Path(inspect.getfile(tool.handler)).resolve().relative_to(ROOT)
            effect = "May change state" if tool.mutates else "Inspect"
            lines.append(f"| `{tool.name}` | {arguments} | {effect} | {tool.description} | [{source.name}](../../{source.as_posix()}) |")
        lines.append("")
    return "\n".join(lines)


def verify_links(paths):
    issues = []
    for path in paths:
        for link in re.findall(r"\]\(([^)]+)\)", path.read_text(encoding="utf-8-sig")):
            target = link.strip().split("#", 1)[0]
            if not target or re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target):
                continue
            if not (path.parent / target).exists():
                issues.append(f"{path.relative_to(ROOT)}: missing {target}")
    return issues


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = {CATALOG: catalog()}
    skills = sorted(CANONICAL.glob("*/SKILL.md"))
    issues = []
    if not skills:
        issues.append("No project skills found.")
    for skill in skills:
        content = skill.read_text(encoding="utf-8")
        frontmatter = content.split("---\n", 2)
        metadata = frontmatter[1] if len(frontmatter) == 3 and not frontmatter[0] else ""
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", skill.parent.name):
            issues.append(f"Invalid skill folder: {skill.parent.name}")
        if not re.search(rf"^name: {re.escape(skill.parent.name)}$", metadata, re.M) or not re.search(r"^description: \S", metadata, re.M):
            issues.append(f"Invalid skill metadata: {skill.relative_to(ROOT)}")
        expected[MIRROR / skill.relative_to(CANONICAL)] = content
    for path, content in expected.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                issues.append(f"Regenerate {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    extras = set(MIRROR.glob("*/SKILL.md")) - expected.keys()
    issues.extend(f"Unexpected mirror: {path.relative_to(ROOT)}" for path in sorted(extras))
    markdown = [*ROOT.glob("*.md"), *(ROOT / "docs").rglob("*.md"), *skills, *MIRROR.glob("*/SKILL.md")]
    issues.extend(verify_links(markdown))
    for issue in issues:
        print(issue, file=sys.stderr)
    if issues:
        return 1
    print(f"Documentation, local links and {len(skills)} project skill pairs are consistent.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
